// Downloads the two bundled type families once, at development time, into public/fonts.
// The dashboard never requests a font from the network at runtime: fonts.css points at these files.
//
//   npm run fonts
//
// Latin + Cyrillic subsets only (the dashboard ships ru and en). When the download fails the script
// leaves fonts.css without @font-face rules, and the CSS stack falls back to system-ui.

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const fontsDir = resolve(root, "public/fonts");
const cssFile = resolve(root, "src/styles/fonts.css");

// A current Chrome UA makes Google Fonts answer with woff2 and variable-font ranges.
const userAgent =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

const families = [
  { id: "Onest", query: "family=Onest:wght@400..700" },
  { id: "JetBrainsMono", query: "family=JetBrains+Mono:wght@400..700" },
];

const subsets = ["cyrillic", "latin"];

const header = `/* Generated by scripts/fetch-fonts.mjs - do not edit by hand.
   Onest and JetBrains Mono, latin + cyrillic subsets, bundled locally: no network request at runtime. */`;

function parseBlocks(css) {
  const blocks = [];
  const re = /\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([^}]+)\}/g;
  let match;
  while ((match = re.exec(css)) !== null) {
    const [, subset, body] = match;
    const url = /url\((https:[^)]+)\)/.exec(body)?.[1];
    const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1]?.trim();
    const weight = /font-weight:\s*([^;]+);/.exec(body)?.[1]?.trim() ?? "400";
    const style = /font-style:\s*([^;]+);/.exec(body)?.[1]?.trim() ?? "normal";
    if (url && range) {
      blocks.push({ subset, url, range, weight, style });
    }
  }
  return blocks;
}

const faces = [];

for (const family of families) {
  const cssUrl = `https://fonts.googleapis.com/css2?${family.query}&display=swap`;
  const response = await fetch(cssUrl, { headers: { "user-agent": userAgent } });
  if (!response.ok) {
    throw new Error(`${family.id}: Google Fonts answered ${response.status}`);
  }

  const blocks = parseBlocks(await response.text());
  const picked = blocks.filter((block) => subsets.includes(block.subset));
  if (picked.length === 0) {
    throw new Error(`${family.id}: no latin/cyrillic blocks in the stylesheet`);
  }

  for (const block of picked) {
    const weightSuffix = block.weight.includes(" ") ? "" : `-${block.weight}`;
    const file = `${family.id}-${block.subset}${weightSuffix}.woff2`;
    const binary = await fetch(block.url, { headers: { "user-agent": userAgent } });
    if (!binary.ok) {
      throw new Error(`${family.id} ${block.subset}: ${binary.status}`);
    }

    await writeFile(resolve(fontsDir, file), Buffer.from(await binary.arrayBuffer()));
    faces.push(
      [
        "@font-face {",
        `  font-family: "${family.id === "JetBrainsMono" ? "JetBrains Mono" : family.id}";`,
        `  font-style: ${block.style};`,
        `  font-weight: ${block.weight};`,
        "  font-display: swap;",
        `  src: url("/fonts/${file}") format("woff2");`,
        `  unicode-range: ${block.range};`,
        "}",
      ].join("\n"),
    );
    console.log(`${family.id} ${block.subset} ${block.weight} -> public/fonts/${file}`);
  }
}

await mkdir(fontsDir, { recursive: true });
await writeFile(cssFile, `${header}\n\n${faces.join("\n\n")}\n`);
console.log(`wrote ${faces.length} @font-face rules to src/styles/fonts.css`);
